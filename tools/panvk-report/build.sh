#!/bin/sh
# build.sh [outdir] — panvk-report.exe (x86-64 Windows; runs in x86-64 and
# ARM64EC Winlator containers). Needs mingw-w64 (x86_64-w64-mingw32-gcc),
# glslangValidator, xxd and the Vulkan headers (Mesa's include/ or the
# system's).
set -eu
DIR="$(cd "$(dirname "$0")" && pwd)"
OUT="${1:-$DIR/../../out}"; mkdir -p "$OUT"
T="$(mktemp -d)"
for s in simple largewg; do
  glslangValidator -V "$DIR/$s.comp" -o "$T/$s.spv" >/dev/null
  (cd "$T" && xxd -i "$s.spv" | sed 's/unsigned char/static const unsigned char/; s/unsigned int .*//') > "$T/$s.h"
done
# SPIR-V as uint32 for the pCode pointer: the arrays are 4-byte aligned below.
{
  echo '/* Generated by build.sh from simple.comp and largewg.comp. */'
  for s in simple largewg; do
    sed "s/static const unsigned char ${s}_spv\[\]/__attribute__((aligned(4))) static const unsigned char ${s}_spv_bytes[]/" "$T/$s.h"
    echo "#define ${s}_spv ((const uint32_t *)${s}_spv_bytes)"
  done
} > "$T/shaders.h"
INC="${VULKAN_INCLUDE:-}"
if [ -z "$INC" ]; then
  for d in "$DIR/../../work/mesa/include" "$HOME/src/mesa-up/include" /usr/include; do
    [ -f "$d/vulkan/vulkan.h" ] && INC="$d" && break
  done
fi
x86_64-w64-mingw32-gcc -O2 -Wall -Wno-missing-braces -I"$T" -I"$INC" \
  "$DIR/panvk-report.c" -o "$OUT/panvk-report.exe" -static -ldxguid -luser32
rm -rf "$T"
echo "$OUT/panvk-report.exe"
